const store: Record<string,string> = {};
(globalThis as any).localStorage = { getItem: (k:string)=>store[k] ?? null, setItem: (k:string,v:string)=>{store[k]=v;} };
(globalThis as any).window = { dispatchEvent(){} };
(globalThis as any).CustomEvent = class {};
const m = await import("./useTfl.ts");
let d: any = (m as any).useTfl();
const ok = (c: boolean, msg: string) => { console.log((c ? "PASS " : "FAIL ") + msg); if (!c) process.exitCode = 1; };
ok(d.locations[0].owner === "o1", "location owner migrated from name to id");
ok(d.bookings[1].location === "l1" && d.bookings[1].production === "p2", "booking links are ids");
ok(m.refLabel(d, "owners", "o1") === "Sample Villa Holdings", "refLabel resolves id");
ok(m.relatedTo(d, "locations", "l1").some((g: any) => g.mod === "bookings"), "location l1 shows linked booking");
ok(m.bookingClashes(d.bookings).size === 0, "no false clashes");
m.tflActions.save("bookings", { location: "l1", production: "p1", startDate: d.bookings[1].startDate, endDate: d.bookings[1].endDate, status: "Hold", id: "bx" });
d = m.useTfl();
ok(m.bookingClashes(d.bookings).has("bx"), "clash detected on same location id");
m.tflActions.remove("locations", "l1");
d = m.useTfl();
ok(d.bookings.find((b:any)=>b.id==="b2").location === "", "deleting a location blanks links to it");
m.tflActions.clearSamples();
d = m.useTfl();
ok(d.bookings.every((b:any)=>b.location === "" || d.locations.some((l:any)=>l.id===b.location)), "no dangling links after clearing samples");
